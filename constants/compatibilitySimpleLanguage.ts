// Helper functions
export function getCompatibilityTerm(
  language: 'en' | 'fr' | 'ar',
  key: keyof typeof COMPATIBILITY_TERMS.en
) {
  return COMPATIBILITY_TERMS[language][key];
}

export function getScoreRange(score: number, language: 'en' | 'fr' | 'ar' = 'en') {
  const ranges = COMPATIBILITY_TERMS[language].scoreLegend.ranges;
  
  if (score >= 85) return ranges.excellent;
  if (score >= 75) return ranges.veryGood;
  if (score >= 65) return ranges.good;
  if (score >= 50) return ranges.moderate;
  return ranges.challenging;
}
